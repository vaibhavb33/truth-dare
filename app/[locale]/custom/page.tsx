import React from 'react';
import type { Metadata } from 'next';
import { notFound } from 'next/navigation';
import { ALL_LOCALES, Locale, SUPPORTED_LOCALES } from '@/lib/i18n/config';
import { getTranslations } from '@/lib/i18n/translations';
import { generateLocalizedMetadata } from '@/lib/i18n/seo';
import { Breadcrumbs } from '@/components/seo/Breadcrumbs';
import { CustomDeckClient } from '@/components/custom/CustomDeckClient';

interface LocalizedCustomProps {
  params: Promise<{ locale: string }>;
}

export function generateStaticParams() {
  return ALL_LOCALES.map((locale) => ({ locale }));
}

export async function generateMetadata({ params }: LocalizedCustomProps): Promise<Metadata> {
  const { locale } = await params;
  if (!ALL_LOCALES.includes(locale as Locale)) return {};

  const dict = getTranslations(locale as Locale);
  const langMeta = SUPPORTED_LOCALES[locale as Locale];

  return generateLocalizedMetadata({
    locale: locale as Locale,
    subpath: '/custom',
    overrideTitle: `${dict.nav.customDeck} Studio — Asteria (${langMeta.nativeName})`,
    overrideDescription: 'Create, edit, and share custom Truth or Dare decks with friends.',
  });
}

export default async function LocalizedCustomPage({ params }: LocalizedCustomProps) {
  const { locale } = await params;
  if (!ALL_LOCALES.includes(locale as Locale)) {
    notFound();
  }

  const dict = getTranslations(locale as Locale);

  return (
    <>
      <Breadcrumbs items={[{ label: dict.nav.customDeck }]} />
      <CustomDeckClient />
    </>
  );
}
